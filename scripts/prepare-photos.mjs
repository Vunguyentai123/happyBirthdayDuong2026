// Đọc ảnh gốc từ photos-source/, xoay theo EXIF, xóa metadata (GPS),
// resize cạnh dài tối đa 1600px, xuất WebP ~80, tên ngẫu nhiên,
// sinh src/data/photos.generated.ts
// Chạy: npm run photos
import { readdir, writeFile, mkdir } from 'node:fs/promises'
import { join, extname } from 'node:path'
import { randomBytes } from 'node:crypto'
import { existsSync } from 'node:fs'
import sharp from 'sharp'

const SRC = 'photos-source'
const DEST = 'public/photos'
const OUT = 'src/data/photos.generated.ts'

const exts = new Set(['.jpg', '.jpeg', '.png', '.webp', '.heic', '.heif'])

function randName() {
  return randomBytes(8).toString('hex')
}

async function main() {
  if (!existsSync(SRC)) {
    console.log(`Thiếu thư mục ${SRC}/ — bỏ qua, dùng khung mẫu.`)
    await mkdir(DEST, { recursive: true })
    await writeFile(OUT, 'export const generatedPhotos: string[] = []\n')
    return
  }
  const files = (await readdir(SRC)).filter((f) => exts.has(extname(f).toLowerCase()))
  await mkdir(DEST, { recursive: true })
  const out = []
  for (const f of files.slice(0, 20)) {
    const name = `${randName()}.webp`
    const srcPath = join(SRC, f)
    const destPath = join(DEST, name)
    try {
      await sharp(srcPath)
        .rotate() // theo EXIF
        .resize({ width: 1600, height: 1600, fit: 'inside', withoutEnlargement: true })
        .webp({ quality: 80 })
        .withMetadata({}) // xóa toàn bộ metadata incl. GPS
        .toFile(destPath)
      out.push(`/photos/${name}`)
      console.log(`OK ${f} -> ${name}`)
    } catch (e) {
      console.error(`Lỗi ${f}:`, e)
    }
  }
  await writeFile(
    OUT,
    `// Auto-generated by scripts/prepare-photos.mjs - do not edit by hand.\nexport const generatedPhotos: string[] = ${JSON.stringify(out, null, 2)}\n`,
  )
  console.log(`Xong: ${out.length} ảnh -> ${OUT}`)
}

main()
